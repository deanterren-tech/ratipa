export type GuideScenario = 'dispatcher' | 'admin';

export interface GuideContext {
  scenario: GuideScenario;
  /** Право записи в модуль (tripTimeline) — как canWrite в модуле. */
  canWrite: boolean;
  /** Может создавать рейс: право «Плана дохода» (кнопка «Новый рейс»). */
  canCreateTrip: boolean;
  /** Может править записи «Учёта выезда» (окно периода). */
  canEditBaza: boolean;
  /** Администратор (root_admin/admin) — решение по запросам доступа к плану. */
  isAdmin: boolean;
}

export interface GuideSpotlight {
  /** Селекторы реальных элементов: подсвечивается первый найденный видимый. */
  selectors: string[];
  /** Короткая подпись «что это» рядом со спотлайтом. */
  hint?: string;
}

