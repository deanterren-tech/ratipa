export interface GuideStep {
  id: string;
  /** Короткое название для оглавления. */
  short: string;
  /** Полный заголовок шага. */
  title: string;
  icon: React.ReactNode;
  paragraphs: string[];
  bullets?: string[];
  /** Спотлайт реального элемента; нет элемента — шаг пропускается. */
  spotlight?: GuideSpotlight;
  /** Демо-фрагменты (изолированные данные, guideDemos). */
  demos?: DemoId[];
  /** Показывать встроенную таблицу «Справочник обозначений» (шаг 7). */
  showReference?: boolean;
  /** Кнопка-«финиш» на шаге (закрывает гайд со статусом done). */
  finish?: boolean;
  /** Условие показа шага роли (нет — шаг показывается всем). */
  when?: (ctx: GuideContext) => boolean;
}

